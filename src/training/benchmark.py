"""
KidneyVision-MLOps
Automated Multi-Model Benchmark Runner

Runs the existing training pipeline sequentially for all benchmark models.

Models:
1. VGG16
2. ResNet50
3. InceptionV3
4. EfficientNet-B0
5. EANet
6. CCT
7. SwinTransformer

The benchmark runner:
- Uses the existing train.py pipeline
- Keeps the same random seed/configuration
- Saves individual training logs
- Reads individual metric JSON files
- Creates one consolidated benchmark CSV
- Creates one consolidated benchmark JSON
"""

from pathlib import Path
import argparse
import json
import subprocess
import sys
import time

import pandas as pd


# ---------------------------------------------------------------------
# PROJECT PATHS
# ---------------------------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parents[2]

TRAIN_SCRIPT = (
    PROJECT_ROOT
    / "src"
    / "training"
    / "train.py"
)

ARTIFACTS_DIR = (
    PROJECT_ROOT
    / "artifacts"
)

METRICS_DIR = (
    ARTIFACTS_DIR
    / "metrics"
)

BENCHMARK_DIR = (
    ARTIFACTS_DIR
    / "benchmark"
)

LOG_DIR = (
    BENCHMARK_DIR
    / "logs"
)


# ---------------------------------------------------------------------
# MODELS
# ---------------------------------------------------------------------

MODELS = [
    "VGG16",
    "ResNet50",
    "InceptionV3",
    "EfficientNet-B0",
    "EANet",
    "CCT",
    "SwinTransformer",
]


# ---------------------------------------------------------------------
# SETUP
# ---------------------------------------------------------------------

BENCHMARK_DIR.mkdir(
    parents=True,
    exist_ok=True,
)

LOG_DIR.mkdir(
    parents=True,
    exist_ok=True,
)


# ---------------------------------------------------------------------
# ARGUMENTS
# ---------------------------------------------------------------------

def parse_arguments():

    parser = argparse.ArgumentParser(
        description="Run KidneyVision multi-model benchmark."
    )

    parser.add_argument(
        "--epochs",
        type=int,
        default=10,
        help="Number of epochs for every model.",
    )

    parser.add_argument(
        "--batch-size",
        type=int,
        default=16,
        help="Training batch size.",
    )

    parser.add_argument(
        "--learning-rate",
        type=float,
        default=1e-4,
        help="Learning rate.",
    )

    parser.add_argument(
        "--models",
        nargs="+",
        default=MODELS,
        choices=MODELS,
        help="Models to benchmark.",
    )

    parser.add_argument(
        "--continue-on-error",
        action="store_true",
        help="Continue with remaining models if one model fails.",
    )

    return parser.parse_args()


# ---------------------------------------------------------------------
# METRIC EXTRACTION
# ---------------------------------------------------------------------

def find_metric(
    data,
    possible_keys,
):
    """
    Recursively search a JSON object for a metric.

    This makes the benchmark compatible with small changes
    in the metrics JSON structure.
    """

    if isinstance(data, dict):

        for key in possible_keys:

            if key in data:

                value = data[key]

                if isinstance(value, (int, float)):

                    return float(value)

        for value in data.values():

            result = find_metric(
                value,
                possible_keys,
            )

            if result is not None:
                return result

    elif isinstance(data, list):

        for item in data:

            result = find_metric(
                item,
                possible_keys,
            )

            if result is not None:
                return result

    return None


# ---------------------------------------------------------------------
# READ MODEL METRICS
# ---------------------------------------------------------------------

def read_model_metrics(
    model_name,
):
    """
    Read metrics generated by train.py.
    """

    filename = (
        model_name
        .lower()
        .replace("-", "_")
        + "_metrics.json"
    )

    metrics_path = (
        METRICS_DIR
        / filename
    )

    if not metrics_path.exists():

        print(
            f"Warning: metrics file not found:\n"
            f"{metrics_path}"
        )

        return {
            "model": model_name,
            "status": "NO_METRICS",
            "accuracy": None,
            "precision": None,
            "recall": None,
            "f1": None,
            "metrics_file": str(metrics_path),
        }

    try:

        with open(
            metrics_path,
            "r",
            encoding="utf-8",
        ) as file:

            data = json.load(file)

    except Exception as error:

        print(
            f"Could not read metrics for {model_name}: "
            f"{error}"
        )

        return {
            "model": model_name,
            "status": "METRICS_READ_ERROR",
            "accuracy": None,
            "precision": None,
            "recall": None,
            "f1": None,
            "metrics_file": str(metrics_path),
        }

    accuracy = find_metric(
        data,
        [
            "test_accuracy",
            "accuracy",
        ],
    )

    precision = find_metric(
        data,
        [
            "test_precision",
            "test_precision_macro",
            "precision",
            "macro_precision",
        ],
    )

    recall = find_metric(
        data,
        [
            "test_recall",
            "test_recall_macro",
            "recall",
            "macro_recall",
        ],
    )

    f1 = find_metric(
        data,
        [
            "test_f1",
            "test_f1_macro",
            "f1",
            "macro_f1",
        ],
    )

    return {
        "model": model_name,
        "status": "SUCCESS",
        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "metrics_file": str(metrics_path),
    }


# ---------------------------------------------------------------------
# RUN ONE MODEL
# ---------------------------------------------------------------------

def run_model(
    model_name,
    epochs,
    batch_size,
    learning_rate,
):
    """
    Run train.py for one model.
    """

    print("\n")
    print("=" * 70)
    print(f"BENCHMARK MODEL: {model_name}")
    print("=" * 70)

    command = [
        sys.executable,
        str(TRAIN_SCRIPT),
        "--model",
        model_name,
        "--epochs",
        str(epochs),
        "--batch-size",
        str(batch_size),
        "--learning-rate",
        str(learning_rate),
    ]

    print("\nCommand:")
    print(" ".join(command))

    log_path = (
        LOG_DIR
        / (
            model_name
            .lower()
            .replace("-", "_")
            + ".log"
        )
    )

    start_time = time.time()

    try:

        with open(
            log_path,
            "w",
            encoding="utf-8",
        ) as log_file:

            process = subprocess.run(
                command,
                cwd=PROJECT_ROOT,
                stdout=log_file,
                stderr=subprocess.STDOUT,
                text=True,
            )

        elapsed_time = (
            time.time() - start_time
        )

        if process.returncode != 0:

            print(
                f"\n{model_name} FAILED."
            )

            print(
                f"Check log:\n{log_path}"
            )

            return {
                "model": model_name,
                "status": "FAILED",
                "accuracy": None,
                "precision": None,
                "recall": None,
                "f1": None,
                "training_time_seconds": round(
                    elapsed_time,
                    2,
                ),
                "log_file": str(log_path),
            }

        print(
            f"\n{model_name} training completed."
        )

        print(
            f"Training time: "
            f"{elapsed_time:.2f} seconds"
        )

        metrics = read_model_metrics(
            model_name
        )

        metrics[
            "training_time_seconds"
        ] = round(
            elapsed_time,
            2,
        )

        metrics[
            "log_file"
        ] = str(log_path)

        return metrics

    except Exception as error:

        elapsed_time = (
            time.time() - start_time
        )

        print(
            f"\nUnexpected error while running "
            f"{model_name}: {error}"
        )

        return {
            "model": model_name,
            "status": "EXCEPTION",
            "accuracy": None,
            "precision": None,
            "recall": None,
            "f1": None,
            "training_time_seconds": round(
                elapsed_time,
                2,
            ),
            "log_file": str(log_path),
        }


# ---------------------------------------------------------------------
# SAVE BENCHMARK RESULTS
# ---------------------------------------------------------------------

def save_results(
    results,
    epochs,
    batch_size,
    learning_rate,
):
    """
    Save consolidated benchmark results.
    """

    dataframe = pd.DataFrame(
        results
    )

    # -------------------------------------------------------------
    # Sort successful models by F1
    # -------------------------------------------------------------

    if "f1" in dataframe.columns:

        dataframe = dataframe.sort_values(
            by="f1",
            ascending=False,
            na_position="last",
        )

    csv_path = (
        BENCHMARK_DIR
        / "benchmark_results.csv"
    )

    dataframe.to_csv(
        csv_path,
        index=False,
    )

    # -------------------------------------------------------------
    # JSON
    # -------------------------------------------------------------

    json_output = {
        "benchmark_configuration": {
            "models": [
                result["model"]
                for result in results
            ],
            "epochs": epochs,
            "batch_size": batch_size,
            "learning_rate": learning_rate,
        },
        "results": results,
    }

    json_path = (
        BENCHMARK_DIR
        / "benchmark_results.json"
    )

    with open(
        json_path,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            json_output,
            file,
            indent=4,
        )

    return csv_path, json_path, dataframe


# ---------------------------------------------------------------------
# PRINT SUMMARY
# ---------------------------------------------------------------------

def print_summary(
    dataframe,
):
    """
    Print final benchmark table.
    """

    print("\n")
    print("=" * 90)
    print("FINAL MODEL BENCHMARK")
    print("=" * 90)

    display_columns = [
        "model",
        "status",
        "accuracy",
        "precision",
        "recall",
        "f1",
        "training_time_seconds",
    ]

    available_columns = [
        column
        for column in display_columns
        if column in dataframe.columns
    ]

    summary = dataframe[
        available_columns
    ].copy()

    # -------------------------------------------------------------
    # Format metrics
    # -------------------------------------------------------------

    for column in [
        "accuracy",
        "precision",
        "recall",
        "f1",
    ]:

        if column in summary.columns:

            summary[column] = summary[
                column
            ].apply(
                lambda value:
                f"{value:.4f}"
                if pd.notna(value)
                else "N/A"
            )

    if (
        "training_time_seconds"
        in summary.columns
    ):

        summary[
            "training_time_seconds"
        ] = summary[
            "training_time_seconds"
        ].apply(
            lambda value:
            f"{value:.2f}"
            if pd.notna(value)
            else "N/A"
        )

    print(
        summary.to_string(
            index=False
        )
    )

    # -------------------------------------------------------------
    # Best model
    # -------------------------------------------------------------

    successful = dataframe[
        dataframe["status"]
        == "SUCCESS"
    ].copy()

    successful = successful[
        successful["f1"].notna()
    ]

    if not successful.empty:

        best_row = successful.loc[
            successful["f1"].idxmax()
        ]

        print("\n" + "=" * 70)
        print("CURRENT BEST MODEL")
        print("=" * 70)

        print(
            f"Model     : {best_row['model']}"
        )

        print(
            f"Accuracy  : {best_row['accuracy']:.4f}"
        )

        print(
            f"Precision : {best_row['precision']:.4f}"
        )

        print(
            f"Recall    : {best_row['recall']:.4f}"
        )

        print(
            f"F1        : {best_row['f1']:.4f}"
        )

    else:

        print(
            "\nNo successful benchmark results "
            "available."
        )


# ---------------------------------------------------------------------
# MAIN
# ---------------------------------------------------------------------

def main():

    args = parse_arguments()

    print("=" * 70)
    print("KIDNEYVISION - 7 MODEL BENCHMARK")
    print("=" * 70)

    print(
        f"\nProject root   : {PROJECT_ROOT}"
    )

    print(
        f"Training script: {TRAIN_SCRIPT}"
    )

    print(
        f"Models         : {args.models}"
    )

    print(
        f"Epochs         : {args.epochs}"
    )

    print(
        f"Batch size     : {args.batch_size}"
    )

    print(
        f"Learning rate  : {args.learning_rate}"
    )

    print(
        "\nImportant:"
    )

    print(
        "The benchmark uses the currently "
        "available 100 verified local images."
    )

    print(
        "The 12,446 CSV metadata records are "
        "NOT treated as 12,446 available images."
    )

    # -------------------------------------------------------------
    # Validate training script
    # -------------------------------------------------------------

    if not TRAIN_SCRIPT.exists():

        raise FileNotFoundError(
            f"Training script not found:\n"
            f"{TRAIN_SCRIPT}"
        )

    # -------------------------------------------------------------
    # Run models
    # -------------------------------------------------------------

    results = []

    total_start = time.time()

    for model_name in args.models:

        result = run_model(
            model_name=model_name,
            epochs=args.epochs,
            batch_size=args.batch_size,
            learning_rate=args.learning_rate,
        )

        results.append(result)

        if (
            result["status"] != "SUCCESS"
            and not args.continue_on_error
        ):

            print(
                "\nBenchmark stopped because "
                f"{model_name} failed."
            )

            print(
                "Use --continue-on-error to "
                "continue with remaining models."
            )

            break

    total_time = (
        time.time() - total_start
    )

    # -------------------------------------------------------------
    # Save results
    # -------------------------------------------------------------

    csv_path, json_path, dataframe = (
        save_results(
            results=results,
            epochs=args.epochs,
            batch_size=args.batch_size,
            learning_rate=args.learning_rate,
        )
    )

    # -------------------------------------------------------------
    # Summary
    # -------------------------------------------------------------

    print_summary(
        dataframe
    )

    print("\n" + "=" * 70)
    print("BENCHMARK ARTIFACTS")
    print("=" * 70)

    print(
        f"CSV  : {csv_path}"
    )

    print(
        f"JSON : {json_path}"
    )

    print(
        f"Logs : {LOG_DIR}"
    )

    print(
        f"\nTotal benchmark time: "
        f"{total_time:.2f} seconds"
    )

    print("\nBENCHMARK COMPLETE")


# ---------------------------------------------------------------------
# ENTRY POINT
# ---------------------------------------------------------------------

if __name__ == "__main__":
    main()